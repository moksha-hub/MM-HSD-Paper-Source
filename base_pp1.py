# ── Extract 1024-dim wav2vec2 features ───────────────
# Model: jonatasgrosman/wav2vec2-large-xlsr-53-english
# Output format: CSV with columns [file_name, feature_0, ..., feature_1023]

import csv, torch, numpy as np, soundfile as sf
from transformers import Wav2Vec2Processor, Wav2Vec2Model
from tqdm.notebook import tqdm

MODEL_ID = 'jonatasgrosman/wav2vec2-large-xlsr-53-english'
device   = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

print(f'Loading wav2vec2 on {device} (~1.2 GB download on first run)...')
processor = Wav2Vec2Processor.from_pretrained(MODEL_ID)
w2v_model = Wav2Vec2Model.from_pretrained(MODEL_ID).to(device)
w2v_model.eval()
print('✅ wav2vec2 loaded')

HEADER = ['file_name'] + [f'feature_{i}' for i in range(1024)]
MAX_AUDIO_SEC = 90  # skip files longer than 10 min to avoid OOM

def extract_w2v_features(wav_path: Path) -> np.ndarray:
    """Returns 1024-dim mean-pooled last hidden state."""
    audio, sr = sf.read(str(wav_path))
    assert sr == 16000, f'Expected 16kHz, got {sr}'
    if audio.ndim > 1:
        audio = audio.mean(axis=1)  # ensure mono
    # Cap at MAX_AUDIO_SEC to avoid OOM on T4 (16 GB VRAM)
    audio = audio[:MAX_AUDIO_SEC * 16000]
    inputs = processor(audio, sampling_rate=16000, return_tensors='pt', padding=True)
    with torch.no_grad():
        outputs = w2v_model(inputs.input_values.to(device))
    return outputs.last_hidden_state.squeeze(0).mean(0).cpu().numpy()

