import subprocess
from tqdm.notebook import tqdm

def extract_wav(video_path: Path, out_dir: Path) -> bool:
    """Extract mono 16kHz PCM WAV. Returns True if done, False on error."""
    out_wav = out_dir / (video_path.stem + '.wav')
    if out_wav.exists() and out_wav.stat().st_size > 1000:
        return True  # already done
    cmd = [
        'ffmpeg', '-i', str(video_path),
        '-ac', '1',           # mono
        '-ar', '16000',       # 16 kHz (required by wav2vec2 + Whisper)
        '-sample_fmt', 's16', # PCM 16-bit
        '-vn',                # no video output
        str(out_wav), '-y', '-loglevel', 'error'
    ]
    result = subprocess.run(cmd, capture_output=True)
    return result.returncode == 0

