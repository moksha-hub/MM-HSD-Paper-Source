def encode_text(text: str) -> list:
    """Returns 768-dim [CLS] last-layer embedding."""
    if not text or not text.strip():
        text = '[empty]'  # graceful fallback
    inputs = tokenizer(
        text, return_tensors='pt',
        truncation=True, max_length=512, padding=True
    ).to(device)
    with torch.no_grad():
        out = bert_mdl(**inputs, output_hidden_states=True)
    cls_emb = out.hidden_states[-1][:, 0, :].squeeze(0)
    return cls_emb.cpu().numpy().tolist()

